"""Does weekday vs weekend explain the rhythm continuum or the group instability? (2022 validation; development)

Usage:
    python scripts/weekday_weekend.py

Uses the nine frozen 80-epoch v1 models as three disjoint 3-model ensembles (A = 42-44, B = 45-47, C = 48-50;
concatenated timing posterior means). Day type from TUDIARYDAY (weekend = Saturday or Sunday; holidays
counted by weekday). For k in {4, 6}:
- pooled: k-means fitted on all train days, ARI between ensembles evaluated on weekday and on weekend
  validation days separately;
- stratified: k-means fitted separately on weekday train days and weekend train days, ARI on the matching
  validation days.
If mixing day types caused the instability, stratified ARI should be clearly higher than pooled ARI on the
same days. Also reports how much day type shifts the continuum axes and simple rhythm measures.
Writes docs/weekday_weekend.md (not a held-out test).
"""

from __future__ import annotations

import importlib.util
import sys
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import adjusted_rand_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.evaluation import v3_metrics as M  # noqa: E402
from src.models.train import load_checkpoint, posterior_means  # noqa: E402


def _load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / file)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ca = _load("ca", "scripts/continuum_axes.py")
ENS = {"A": (42, 43, 44), "B": (45, 46, 47), "C": (48, 49, 50)}
KS = (4, 6)


def main() -> None:
    z = np.load(ROOT / "data/processed/2022/sequences.npz")
    cats = z["categories"].tolist()
    seq, ids = z["seq"], z["case_ids"]
    tr, va = z["split"] == "train", z["split"] == "val"
    meta = pd.read_parquet(ROOT / "data/processed/2022/metadata.parquet").set_index("case_id")
    weekend = meta.loc[ids, "TUDIARYDAY"].isin([1, 7]).to_numpy()
    emb = {s: posterior_means(load_checkpoint(Path(sorted(Path(ROOT).glob(p))[-1]) / "best.pt")[0],
                              torch.from_numpy(seq).long())["timing_mu"] for s, p in ca.MODELS.items()}
    reps = {n: np.hstack([emb[s] for s in ss]) for n, ss in ENS.items()}

    rows = []
    for k in KS:
        pooled = {n: M.kmeans_labels(R[tr], R, k, 0, scale=False) for n, R in reps.items()}
        for name, mask in (("weekday", ~weekend), ("weekend", weekend)):
            ev = va & mask
            strat = {n: M.kmeans_labels(R[tr & mask], R[ev], k, 0, scale=False) for n, R in reps.items()}
            p_ari = [adjusted_rand_score(pooled[a][ev], pooled[b][ev]) for a, b in combinations(ENS, 2)]
            s_ari = [adjusted_rand_score(strat[a], strat[b]) for a, b in combinations(ENS, 2)]
            rows.append({"k": k, "day_type": name, "n_val_days": int(ev.sum()),
                         "pooled_ARI": float(np.mean(p_ari)), "pooled_ARI_sd": float(np.std(p_ari)),
                         "stratified_ARI": float(np.mean(s_ari)), "stratified_ARI_sd": float(np.std(s_ari))})
        all_ari = [adjusted_rand_score(pooled[a][va], pooled[b][va]) for a, b in combinations(ENS, 2)]
        rows.append({"k": k, "day_type": "all (pooled)", "n_val_days": int(va.sum()),
                     "pooled_ARI": float(np.mean(all_ari)), "pooled_ARI_sd": float(np.std(all_ari)),
                     "stratified_ARI": np.nan, "stratified_ARI_sd": np.nan})
    ari = pd.DataFrame(rows)
    for r in rows:
        print(r, flush=True)

    # How much does day type shift the continuum axes and the simple rhythm measures?
    axes = pd.read_csv(ROOT / "outputs/continuum/axes_val_2022.csv", dtype={"case_id": str}).set_index("case_id")
    rm = ca.rhythm_measures(seq[va], cats)
    rm.index = ids[va]
    df = rm.join(axes[["axis1", "axis2"]])
    df["day_type"] = np.where(weekend[va], "weekend", "weekday")
    cols = ["axis1", "axis2", "sleep_midpoint_h", "wake_h", "bedtime_h", "work_centre_h", "transitions", "work_min"]
    means = df.groupby("day_type")[cols].mean().T
    sd = df[cols].std()
    means["difference_in_SD"] = (means["weekend"] - means["weekday"]) / sd
    # Share of each axis's variance explained by day type (eta squared).
    eta = {c: float(((df.groupby("day_type")[c].transform("mean") - df[c].mean()) ** 2).sum() /
                    ((df[c] - df[c].mean()) ** 2).sum()) for c in ("axis1", "axis2")}

    lines = ["# Weekday vs weekend (2022 validation; development result — for review)", "",
             "Generated by `scripts/weekday_weekend.py`. Nine frozen 80-epoch v1 models as three disjoint 3-model",
             "ensembles; weekend = Saturday/Sunday diary day (TUDIARYDAY). k-means n_init = 50 on concatenated timing",
             "posterior means, fitted on 2022 train days (pooled: all days; stratified: same day type only).", "",
             "## Does separating day types make groups more reproducible?", "",
             "ARI between ensembles (mean ± SD over 3 pairs), evaluated on the same validation days.", "",
             ari.to_markdown(index=False, floatfmt=".3f"), "",
             "## How much does day type shift the rhythm?", "",
             f"Share of axis variance explained by day type: axis 1 {eta['axis1']:.3f}, axis 2 {eta['axis2']:.3f}.", "",
             means.to_markdown(floatfmt=".2f"), ""]
    (ROOT / "docs/weekday_weekend.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
