"""Survey-weighted sensitivity analysis (2022 validation diaries; development result).

Usage:
    python scripts/weighted_sensitivity.py

All earlier results are unweighted. ATUS deliberately oversamples weekends and some groups, so any statement
about how common a rhythm is needs the final weight TUFINLWGT, with standard errors from the 160 replicate
final weights (FINLWGT001-160). Per the ATUS User's Guide section 7.5:
    Var(Ŷ0) = (4/160) Σ_r (Ŷ_r - Ŷ0)².
Estimates are weighted means / shares Σ w y / Σ w over the 1,627 validation diaries (a random 20% respondent
subsample, so estimates are less precise than full-sample ones).

Reports, unweighted vs weighted (± replicate SE):
1. shares of days in the low / middle / high bands of continuum axes 1 and 2 (docs/continuum_axes.md);
2. mean rhythm measures, overall and by day type;
3. shares of the v3 ensemble-A groups (k = 6, the 2025-test configuration) on validation days;
4. a separation check: tree-probe R² of activity totals from the amount latent and clock-timing gain from
   the timing latent, scored unweighted vs weighted (probes fitted unweighted on train), for 3 models.
Writes docs/weighted_sensitivity.md.
"""

from __future__ import annotations

import importlib.util
import sys
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.metrics import r2_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.baselines.features import TimingFeaturizer, totals_features  # noqa: E402
from src.data.rasterize import category_counts  # noqa: E402
from src.evaluation import v3_metrics as M  # noqa: E402
from src.evaluation.separation import PROBE_TARGETS  # noqa: E402
from src.models.train import load_checkpoint, posterior_means  # noqa: E402


def _load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / file)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ca = _load("ca", "scripts/continuum_axes.py")
v3f = _load("v3f", "scripts/evaluate_v3_final.py")
N_REP = 160


def load_weights(case_ids: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    meta = pd.read_parquet(ROOT / "data/processed/2022/metadata.parquet").set_index("case_id")
    w0 = meta.loc[case_ids, "TUFINLWGT"].to_numpy(float)
    with zipfile.ZipFile(ROOT / "data/raw/2022/atuswgts-2022.zip") as zf:
        name = next(n for n in zf.namelist() if n.endswith(".dat"))
        rep = pd.read_csv(zf.open(name), dtype={"TUCASEID": str}).set_index("TUCASEID")
    cols = [f"FINLWGT{i:03d}" for i in range(1, N_REP + 1)]
    assert set(cols) <= set(rep.columns), "unexpected replicate weight column names"
    W = rep.loc[case_ids, cols].to_numpy(float)
    return w0, W


def wmean(y: np.ndarray, w0: np.ndarray, W: np.ndarray) -> tuple[float, float]:
    """Weighted mean of y (NaNs dropped) with replicate standard error."""
    ok = ~np.isnan(y)
    y, w0, W = y[ok], w0[ok], W[ok]
    est = (w0 * y).sum() / w0.sum()
    reps = (W * y[:, None]).sum(0) / W.sum(0)
    return float(est), float(np.sqrt(4 / N_REP * ((reps - est) ** 2).sum()))


def fmt(est: float, se: float, pct: bool = False) -> str:
    return f"{100 * est:.1f}% ± {100 * se:.1f}" if pct else f"{est:.2f} ± {se:.2f}"


def main() -> None:
    z = np.load(ROOT / "data/processed/2022/sequences.npz")
    cats = z["categories"].tolist()
    C, clock, seq, ids = len(cats), z["clock_features"], z["seq"], z["case_ids"]
    tr, va = z["split"] == "train", z["split"] == "val"
    vid = ids[va]
    w0, W = load_weights(vid)
    ones = np.ones_like(w0)
    meta = pd.read_parquet(ROOT / "data/processed/2022/metadata.parquet").set_index("case_id")
    weekend = meta.loc[vid, "TUDIARYDAY"].isin([1, 7]).to_numpy()
    lines = ["# Survey-weighted sensitivity (2022 validation; development result)", "",
             "Generated by `scripts/weighted_sensitivity.py`. Weighted estimates use TUFINLWGT; ± values are replicate",
             "standard errors from FINLWGT001-160 with Var = (4/160) Σ (Ŷ_r − Ŷ0)² (ATUS User's Guide §7.5). Unweighted",
             "values treat every diary equally, as all earlier results did. 1,627 validation diaries (20% of 2022",
             "respondents), so standard errors are larger than full-sample estimates would have.", "",
             f"Weekend share of diaries: unweighted {weekend.mean():.1%}; weighted {fmt(*wmean(weekend.astype(float), w0, W), pct=True)}.", ""]

    # 1. Continuum bands.
    axes = pd.read_csv(ROOT / "outputs/continuum/axes_val_2022.csv", dtype={"case_id": str}).set_index("case_id").loc[vid]
    lines += ["## 1. Share of days in each rhythm band", "",
              "| Axis | Band | Unweighted | Weighted ± SE |", "| --- | --- | ---: | ---: |"]
    names = {0: "low", 1: "middle", 2: "high"}
    for a in (1, 2):
        b = axes[f"band{a}"].to_numpy()
        for k in range(3):
            y = (b == k).astype(float)
            lines.append(f"| {a} | {names[k]} | {y.mean():.1%} | {fmt(*wmean(y, w0, W), pct=True)} |")
    lines.append("")

    # 2. Rhythm measures.
    rm = ca.rhythm_measures(seq[va], cats)
    lines += ["## 2. Mean rhythm measures", "", "Clock times in hours (sleep midpoint and bedtime run past 24 after midnight).", "",
              "| Measure | Group | Unweighted | Weighted ± SE |", "| --- | --- | ---: | ---: |"]
    for c in ["wake_h", "sleep_midpoint_h", "bedtime_h", "work_centre_h", "transitions", "work_min", "sleep_min"]:
        for g, m in (("all days", np.ones(len(vid), bool)), ("weekday", ~weekend), ("weekend", weekend)):
            y = np.where(m, rm[c].to_numpy(float), np.nan)
            lines.append(f"| {c} | {g} | {np.nanmean(y):.2f} | {fmt(*wmean(y, w0, W))} |")
    lines.append("")

    # 3. v3 ensemble-A groups (k = 6) on validation days.
    emb = {s: posterior_means(load_checkpoint(v3f.latest(p) / "best.pt")[0], torch.from_numpy(seq).long())["timing_mu"]
           for s, p in v3f.MODELS.items() if s in v3f.ENSEMBLES["A"]}
    R = np.hstack([emb[s] for s in v3f.ENSEMBLES["A"]])
    lab = M.kmeans_labels(R[tr], R[va], 6, 0, scale=False)
    lines += ["## 3. Shares of the v3 ensemble-A groups (k = 6)", "",
              "Groups are not reproducible across model sets (docs/v3_k_sweep_ensembles.md); shares are shown only to",
              "show how much weighting moves them.", "", "| Group | Unweighted | Weighted ± SE |", "| --- | ---: | ---: |"]
    for g in range(6):
        y = (lab == g).astype(float)
        lines.append(f"| {g} | {y.mean():.1%} | {fmt(*wmean(y, w0, W), pct=True)} |")
    lines.append("")

    # 4. Separation check, scored with and without weights.
    tot, _ = totals_features(category_counts(seq, C), cats)
    tf = TimingFeaturizer(cats, clock).fit(seq[tr])
    X, fnames = tf.transform(seq), tf.names_
    clock_cols = [fnames.index(t) for t in PROBE_TARGETS["clock"]]
    rows = []
    for s in (42, 43, 44):
        e = posterior_means(load_checkpoint(v3f.latest(v3f.MODELS[s]) / "best.pt")[0], torch.from_numpy(seq).long())
        res = {"seed": s}
        for wname, sw in (("unweighted", ones), ("weighted", w0)):
            r2_tot = []
            for c in M.MAIN:
                y = tot[:, cats.index(c)]
                pred = HistGradientBoostingRegressor(random_state=0).fit(e["amount_mu"][tr], y[tr]).predict(e["amount_mu"][va])
                r2_tot.append(r2_score(y[va], pred, sample_weight=sw))
            gains = []
            both = np.hstack([tot, e["timing_mu"]])
            for j in clock_cols:
                y = X[:, j]
                p0 = HistGradientBoostingRegressor(random_state=0).fit(tot[tr], y[tr]).predict(tot[va])
                p1 = HistGradientBoostingRegressor(random_state=0).fit(both[tr], y[tr]).predict(both[va])
                gains.append(r2_score(y[va], p1, sample_weight=sw) - r2_score(y[va], p0, sample_weight=sw))
            res[f"amount_totalsR2_{wname}"] = float(np.mean(r2_tot))
            res[f"timing_clock_gain_{wname}"] = float(np.mean(gains))
        rows.append(res)
        print(res, flush=True)
    sep = pd.DataFrame(rows)
    lines += ["## 4. Separation check: unweighted vs weighted scoring (v3 40-epoch models, seeds 42-44)", "",
              "Probes fitted unweighted on 2022 train rows; R² on validation computed with and without TUFINLWGT.", "",
              sep.to_markdown(index=False, floatfmt=".3f"), ""]
    (ROOT / "docs/weighted_sensitivity.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
