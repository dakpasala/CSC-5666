"""Aggregate Checkpoint 5 robustness runs: mean and SD over seeds for each variant, with untrained floors.

Usage:
    python scripts/compare_robustness.py

Reads the latest run per <variant>_s<seed> in outputs/checkpoint5_robustness/, computes an untrained-network
reference per seed, and writes outputs/checkpoint5_robustness/{per_run,summary}.csv and
docs/checkpoint5_robustness_report.md. Validation data only (2022); 2023 untouched.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
_spec = importlib.util.spec_from_file_location("cmp4", ROOT / "scripts/compare_checkpoint4.py")
cmp4 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cmp4)

BASE = ROOT / "outputs/checkpoint5_robustness"
CFG = ROOT / "configs/vae_checkpoint5_robustness.yaml"
VARIANTS = ["guided", "guided_l0.3", "guided_l0.1", "no_invariance", "unguided", "joint"]
SEEDS = [42, 43, 44]

KEY_METRICS = [
    ("val_CE", "Validation CE (nats/slot)"), ("val_acc", "Slot accuracy"), ("val_macroF1", "Macro-F1"),
    ("transitions_pred", "Predicted transitions/day (true 14.8)"),
    ("amount_active", "Active amount dims (of 8)"), ("timing_active", "Active timing dims"),
    ("amount_sens_shift", "Amount pair sensitivity, shift"), ("amount_sens_swap", "Amount pair sensitivity, swap"),
    ("timing_sens_shift", "Timing pair sensitivity, shift"), ("timing_sens_swap", "Timing pair sensitivity, swap"),
    ("totalsR2_from_amount", "Totals R², amount latent (linear)"),
    ("knn_totalsR2_from_amount", "Totals R², amount latent (kNN)"),
    ("clock_gain_amount", "Timing gain over totals, amount latent (linear)"),
    ("knn_clock_gain_amount", "Timing gain over totals, amount latent (kNN)"),
    ("clock_gain_timing", "Timing gain over totals, timing latent (linear)"),
    ("knn_clock_gain_timing", "Timing gain over totals, timing latent (kNN)"),
    ("mix_totals_follow_amount", "Mix: totals follow amount source (random pairs)"),
    ("matched_mix_timing_follow_timing", "Mix: timing follows timing source (matched totals)"),
    ("matched_mix_slots_timing_src", "Mix: slot agreement with timing source (matched totals)"),
    ("matched_mix_slots_amount_src", "Mix: slot agreement with amount source (matched totals)"),
    ("acc_amount_fixed", "Accuracy with amount latent fixed"), ("acc_timing_fixed", "Accuracy with timing latent fixed"),
]


def main() -> None:
    rows = []
    for v in VARIANTS:
        for s in SEEDS:
            run = cmp4.latest_run(BASE, f"{v}_s{s}")
            if run is None:
                print(f"missing {v}_s{s}")
                continue
            r = cmp4.row(v, json.loads((run / "eval_best.json").read_text()),
                         yaml.safe_load((run / "resolved_config.yaml").read_text()))
            rows.append({**r, "seed": s, "run": str(run.relative_to(ROOT))})
    for s in SEEDS:
        ref = BASE / f"untrained_reference_s{s}.json"
        if not ref.exists():
            ref.write_text(json.dumps(cmp4.untrained_reference(CFG, seed=s)))
        rows.append({**cmp4.row("untrained", json.loads(ref.read_text()), None), "seed": s})
    df = pd.DataFrame(rows)
    df.to_csv(BASE / "per_run.csv", index=False)

    cols = [c for c, _ in KEY_METRICS if c in df]
    agg = df.groupby("variant", sort=False)[cols].agg(["mean", "std", "count"])
    agg.to_csv(BASE / "summary.csv")
    order = [v for v in [*VARIANTS, "untrained"] if v in agg.index]

    def cell(v: str, c: str) -> str:
        m, sd, n = agg.loc[v, (c, "mean")], agg.loc[v, (c, "std")], agg.loc[v, (c, "count")]
        if pd.isna(m):
            return "—"
        return f"{m:.3f} ± {sd:.3f}" if n > 1 else f"{m:.3f}"

    lines = [
        "# Checkpoint 5 robustness report (validation, 2022)",
        "",
        "Generated by `scripts/compare_robustness.py`. Each trained variant: full 2022 train split (6,509 diaries),",
        "40 epochs, best validation checkpoint, seeds 42/43/44. Values are mean ± SD over seeds, evaluated on the",
        "1,627 validation diaries (probes fitted on train-split embeddings). `untrained` = same architecture with",
        "random weights (one per seed): the floor any learned effect must clear. 2023 untouched.",
        "",
        "| Metric | " + " | ".join(order) + " |",
        "| --- | " + " | ".join("---:" for _ in order) + " |",
        *[f"| {label} | " + " | ".join(cell(v, c) for v in order) + " |" for c, label in KEY_METRICS if c in df],
        "",
        "Runs: " + ", ".join(f"`{r}`" for r in df["run"].dropna()),
        "",
    ]
    (ROOT / "docs/checkpoint5_robustness_report.md").write_text("\n".join(lines))
    print("\n".join(lines[7:7 + len(KEY_METRICS) + 2]))


if __name__ == "__main__":
    main()
