"""Apply the pre-written v2 selection rule (docs/v2_validation_plan.md) to the sweep runs.

Usage:
    python scripts/compare_v2_sweep.py [--base outputs/v2_sweep]

Writes <base>/sweep_table.csv and docs/v2_sweep_report.md. 2022 validation only.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
RUNS = ["sw_base", "sw_observed", "sw_beta0.3", "sw_beta0.1", "sw_condprior", "sw_nopairs"]


def latest(base: Path, name: str) -> Path | None:
    runs = sorted(p for p in base.glob(f"{name}-*") if (p / "eval_best.json").exists())
    return runs[-1] if runs else None


def summarize(name: str, run: Path) -> dict:
    m = json.loads((run / "eval_best.json").read_text())
    cfg = yaml.safe_load((run / "resolved_config.yaml").read_text())
    pred, obs = m["val_exact_budget_predicted"], m["val_exact_budget_observed"]
    s = m["separation"]
    tim = s["probes"]["inputs"]["timing"]
    ps = s["pair_sensitivity_val"]
    mt = s.get("mix_and_match_matched_totals_val") or {}
    lt = m["latents_val"]["timing"]
    return {
        "run": name, "dir": str(run.relative_to(ROOT)), "best_epoch": m["checkpoint_epoch"],
        "beta": cfg["loss"]["beta_timing"], "budget_train": cfg["model"]["budget_source"],
        "cond_prior": cfg["model"]["conditional_prior"], "pairs": bool((cfg.get("pairs") or {}).get("enabled")),
        "CE_pred_budget": pred["cross_entropy"], "CE_obs_budget": obs["cross_entropy"],
        "acc_exact_pred": pred["accuracy"], "macroF1_exact_pred": pred["macro_f1"],
        "transitions_exact_pred": pred["transitions_pred_mean"], "transitions_true": pred["transitions_true_mean"],
        "reassigned_min_pred": pred["reassigned_minutes_per_diary_mean"],
        "acc_argmax": m["val"]["accuracy"],
        "timing_active": lt["active_dims"], "timing_KL": lt["kl_total_mean"],
        "knn_clock_gain": tim["knn_timing_clock_gain_over_true_totals"],
        "knn_frag_gain": tim["knn_frag_gain_over_true_totals"],
        "knn_totalsR2_from_timing": tim["knn_totals_r2"],
        "timing_sens_shift": ps["shift"]["timing"]["median"], "timing_sens_swap": ps["swap"]["timing"]["median"],
        "timing_sens_splitmerge": ps["split_merge"]["timing"]["median"],
        "matched_mix": mt.get("timing_closer_to_timing_source", np.nan),
        "matched_mix_slots_timing_src": mt.get("slot_agreement_with_timing_source", np.nan),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", type=Path, default=ROOT / "outputs/v2_sweep")
    args = ap.parse_args()
    rows = [summarize(n, r) for n in RUNS if (r := latest(args.base, n))]
    df = pd.DataFrame(rows)
    best_ce = df["CE_pred_budget"].min()
    df["eligible"] = (df["CE_pred_budget"] <= 1.05 * best_ce) & (df["timing_active"] >= 4)
    df["timing_gain_mean"] = df[["knn_clock_gain", "knn_frag_gain"]].mean(axis=1)
    elig = df[df["eligible"]].sort_values("matched_mix", ascending=False)
    chosen = None
    if len(elig):
        top = elig[elig["matched_mix"] >= elig["matched_mix"].iloc[0] - 0.01]
        chosen = top.sort_values(["timing_gain_mean", "CE_pred_budget"], ascending=[False, True]).iloc[0]["run"]
    df.to_csv(args.base / "sweep_table.csv", index=False)
    show = ["run", "best_epoch", "eligible", "CE_pred_budget", "CE_obs_budget", "acc_exact_pred", "macroF1_exact_pred",
            "transitions_exact_pred", "timing_active", "timing_KL", "knn_clock_gain", "knn_frag_gain",
            "knn_totalsR2_from_timing", "timing_sens_shift", "timing_sens_swap", "timing_sens_splitmerge", "matched_mix"]
    lines = ["# Model v2 sweep (2022 validation)", "",
             "Generated by `scripts/compare_v2_sweep.py`. Seed 42, 30 epochs, full 2022 train split; 1,627 validation",
             "diaries. CE and exact-budget reconstruction use budgets **predicted** from the amount latent.",
             f"Rule (docs/v2_validation_plan.md): CE ≤ 1.05 × best ({1.05 * best_ce:.3f}) and ≥ 4 active timing dims;",
             "then highest matched-totals mix-and-match; ties within 0.01 → higher mean kNN timing gain → lower CE.", "",
             f"**Chosen: {chosen}**", "", df[show].to_markdown(index=False, floatfmt=".3f"), "",
             f"True transitions per validation day: {df['transitions_true'].iloc[0]:.1f}.", ""]
    (ROOT / "docs/v2_sweep_report.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
